-- 02-rollback.sql
-- ######################################################################
-- ##  MUTATING. PRODUCTION DDL. NEEDS THE USER'S EXPLICIT "YES" IN CHAT ##
-- ##  BEFORE v_mode IS SET TO 'execute'. Default mode is a dry run.     ##
-- ######################################################################
-- PURPOSE: return PRODUCTION (gdakokshfjqljddlrkrh) from stage "bundle-applied"
--          to the exact pre-bundle shape, i.e. undo the canonical bundle
--          (SHA-256 A7878BF3A92587B653159604AED6DF0F959207A9C36958E686729EB215120A1B),
--          WITHOUT deleting any row that existed before the bundle.
--
-- What the bundle added, and what this file removes (nothing else is touched):
--   - 7 new tables (and with them their 6 policies, indexes, constraints, grants):
--     dashboard_batches, dashboard_deliveries, dashboard_rollover_candidates,
--     seed_pool_state, seed_pool_observed_days, seed_pool_assets, seed_pool_snapshots
--   - 19 new functions in public (production had none of these names before; the
--     bundle's second claim_briefing_delivery replaced its own first definition)
--   - on the EXISTING table briefing_deliveries: columns local_date,
--     seed_pool_version, seed_revocation_generation and the partial unique index
--     briefing_deliveries_user_local_date_idx. Its 8 original columns, its rows,
--     its 2 original indexes, its policies, grants and sequence are not touched.
--   The bundle wrote no row into any pre-existing table and no migration-ledger row,
--   so there is nothing else to undo.
--
-- WHEN THIS FILE MAY RUN AT ALL (otherwise it REFUSES):
--   R1. Production guard passes (same checks as 00-production-guard.sql).
--   R2. Stage is exactly "bundle-applied".
--   R3. NOTHING NEW WAS WRITTEN that a drop would destroy:
--       - zero rows in seed_pool_state, seed_pool_assets, seed_pool_snapshots,
--         dashboard_batches, dashboard_deliveries, dashboard_rollover_candidates;
--       - zero briefing_deliveries rows with local_date, seed_pool_version or a
--         non-zero seed_revocation_generation (dropping those columns would erase
--         the per-day identity the new code wrote);
--       - zero storage objects under private-uploads/seed-pool/ (seed PDFs would be
--         orphaned with no record pointing at them);
--       - zero seed_pool_observed_days rows, UNLESS the user explicitly accepts losing
--         them (v_allow_drop_observed_day_markers := true). These rows hold only
--         (owner_id, local_date) markers that the new code writes for every signed-in
--         owner who was shown a feed or digest; they are derived bookkeeping, not
--         user-authored content, but they are rows the new code wrote, so the
--         default refuses.
--   If R3 fails, DO NOT edit this file to force it. The choices are, in order:
--     (a) keep the schema and roll back only the app on Vercel: the old build
--         902eb50 works unchanged with the new schema (see RUNBOOK.md section C);
--     (b) forward-fix;
--     (c) restore the Supabase backup taken before the apply. That loses EVERY write
--         made after the backup (all users, all tables, auth included) and is the
--         user's decision alone.
--   R4. The app is already back on the old build (Vercel instant rollback to
--       902eb50 done and confirmed). SQL cannot see this; RUNBOOK.md step H2 checks it.
--
-- MODES (edit only the four OPERATOR SETTINGS lines inside the block):
--   v_target 'production'          production guard; real target.
--   v_target 'peer-test-rehearsal' requires the peer-test sentinel
--                                  (peer_test_guard.target = cbsbtkvbmvyznerbpmxg),
--                                  skips the production guard, records R3 blockers
--                                  instead of refusing, and is FORCED to dry-run.
--                                  Lets the drop statements run once on real Supabase
--                                  and roll back. It can never change either project.
--   v_mode 'dry-run' (default)     does every check and every drop, verifies the
--                                  pre-bundle shape, then RAISEs
--                                  "PEER_ROLLBACK_DRY_RUN_OK ..." on purpose, so the
--                                  whole block rolls back. Nothing changes.
--   v_mode 'execute'               production only, after the user's explicit yes.
--                                  Same steps; the block then completes and commits.
--                                  The SELECT after the block reports the new stage,
--                                  which must read "pre-bundle".
-- FAIL CLOSED: a NULL or unknown v_mode / v_target is REFUSED before anything else
-- runs; NULL in either boolean setting counts as false; the block can commit only
-- when v_mode is exactly 'execute' AND v_target is exactly 'production'. Any other
-- value ends in the dry-run error, so a typo can never commit.
-- lock_timeout is 5 s for this transaction: if the old app holds briefing_deliveries
-- longer, the block fails with lock_not_available and changes nothing; re-run later.
-- PostgREST reloads its schema cache by itself (event triggers pgrst_ddl_watch /
-- pgrst_drop_watch, present on production per production-default-privileges.json).
-- After an execute: run 01-preflight-readonly.sql; every stop_check must be true
-- again (production equals the 2026-11-03 exports).
-- No psql meta-commands: paste-safe for the Supabase SQL Editor (role postgres).

DO $rollback$
DECLARE
  -- ===================== OPERATOR SETTINGS (edit only these) =====================
  v_target text := 'production';               -- 'production' | 'peer-test-rehearsal'
  v_mode   text := 'dry-run';                  -- 'dry-run' | 'execute' (execute = user said yes)
  v_allow_drop_observed_day_markers boolean := false;   -- R3; true only with the user's yes
  v_storage_checked_in_ui boolean := false;    -- true only if postgres cannot read storage.objects
                                               -- AND the operator saw no seed-pool/ folder in
                                               -- Storage > private-uploads
  -- ===============================================================================
  v_expected_versions CONSTANT text[] := ARRAY[
    '20260424083636','20260428073641','20260429044039','20260505063457','20260915042700',
    '20260915042730','20260915042732','20260915042735','20260915042738','20260915042741',
    '20260915042812'];
  v_versions  text[];
  v_users     bigint;
  v_oldest    timestamptz;
  v_missing   text[];
  v_blockers  text[] := '{}';
  v_n         bigint;
  v_storage   bigint;
  v_counts    jsonb;
  v_bd_before bigint;
  v_bd_after  bigint;
  v_left      text[];
BEGIN
  PERFORM set_config('lock_timeout', '5s', true);

  -- [0] Operator settings: NULL or unknown values fail closed, before anything else --
  IF v_mode IS NULL OR v_mode NOT IN ('dry-run', 'execute') THEN
    RAISE EXCEPTION 'REFUSED: v_mode must be ''dry-run'' or ''execute'' (got %).', coalesce(quote_literal(v_mode), 'NULL');
  END IF;
  IF v_target IS NULL OR v_target NOT IN ('production', 'peer-test-rehearsal') THEN
    RAISE EXCEPTION 'REFUSED: v_target must be ''production'' or ''peer-test-rehearsal'' (got %).', coalesce(quote_literal(v_target), 'NULL');
  END IF;
  v_allow_drop_observed_day_markers := coalesce(v_allow_drop_observed_day_markers, false);
  v_storage_checked_in_ui := coalesce(v_storage_checked_in_ui, false);

  -- [1] Target guard ---------------------------------------------------------------
  IF v_target = 'production' THEN
    IF current_user <> 'postgres' THEN
      RAISE EXCEPTION 'REFUSED (G1): run as role postgres; current_user=%.', current_user;
    END IF;
    IF to_regnamespace('peer_test_guard') IS NOT NULL THEN
      RAISE EXCEPTION 'REFUSED (G2): schema peer_test_guard exists. This is the peer-test project, NOT production. Use v_target := ''peer-test-rehearsal'' there.';
    END IF;
    IF to_regclass('supabase_migrations.schema_migrations') IS NULL THEN
      RAISE EXCEPTION 'REFUSED (G3): supabase_migrations.schema_migrations is absent; production has an 11-row ledger. Stop.';
    END IF;
    EXECUTE 'SELECT coalesce(array_agg(version::text ORDER BY version::text), ''{}''::text[]) FROM supabase_migrations.schema_migrations'
      INTO v_versions;
    IF v_versions IS DISTINCT FROM v_expected_versions THEN
      RAISE EXCEPTION 'REFUSED (G3): migration ledger differs from the production export (rows=%). Stop.', coalesce(array_length(v_versions, 1), 0);
    END IF;
    SELECT count(*), min(created_at) INTO v_users, v_oldest FROM auth.users;
    IF v_users = 0 OR v_oldest IS NULL OR v_oldest >= timestamptz '2026-11-03 00:00:00+00' THEN
      RAISE EXCEPTION 'REFUSED (G4): auth.users has no account created before 2026-11-03 UTC; production has older accounts. Stop.';
    END IF;
    SELECT coalesce(array_agg(t ORDER BY t), '{}'::text[]) INTO v_missing
      FROM unnest(ARRAY['briefing_deliveries','feedback_events','opportunity_pools','private_decisions',
                        'private_paper_pools','profiles','read_items','saved_items','usage_counters']) AS t
     WHERE to_regclass('public.' || t) IS NULL;
    IF cardinality(v_missing) > 0 THEN
      RAISE EXCEPTION 'REFUSED (G5): production public tables missing: %. Stop.', v_missing;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM storage.buckets
                    WHERE id = 'private-uploads' AND public = false AND file_size_limit = 26214400) THEN
      RAISE EXCEPTION 'REFUSED (G6): private bucket private-uploads (26214400 bytes) not found as exported. Stop.';
    END IF;
  ELSIF v_target = 'peer-test-rehearsal' THEN
    IF to_regclass('peer_test_guard.target') IS NULL THEN
      RAISE EXCEPTION 'REFUSED: rehearsal needs the peer-test sentinel peer_test_guard.target; this is not peer-test.';
    END IF;
    EXECUTE 'SELECT count(*) FROM peer_test_guard.target WHERE project_ref = ''cbsbtkvbmvyznerbpmxg''' INTO v_n;
    IF v_n <> 1 THEN
      RAISE EXCEPTION 'REFUSED: peer-test sentinel does not name cbsbtkvbmvyznerbpmxg.';
    END IF;
    v_mode := 'dry-run';  -- a rehearsal can never commit
  ELSE
    RAISE EXCEPTION 'REFUSED: v_target must be ''production'' or ''peer-test-rehearsal'' (got %).', v_target;
  END IF;
  IF v_mode IS NULL OR v_mode NOT IN ('dry-run', 'execute') THEN
    RAISE EXCEPTION 'REFUSED: v_mode must be ''dry-run'' or ''execute'' (got %).', v_mode;
  END IF;

  -- [2] Stage must be bundle-applied (R2) ------------------------------------------
  SELECT coalesce(array_agg(t ORDER BY t), '{}'::text[]) INTO v_missing
    FROM unnest(ARRAY['dashboard_batches','dashboard_deliveries','dashboard_rollover_candidates',
                      'seed_pool_state','seed_pool_observed_days','seed_pool_assets','seed_pool_snapshots']) AS t
   WHERE to_regclass('public.' || t) IS NULL;
  SELECT count(*) INTO v_n FROM information_schema.columns
   WHERE table_schema = 'public' AND table_name = 'briefing_deliveries'
     AND column_name IN ('local_date', 'seed_pool_version', 'seed_revocation_generation');
  IF cardinality(v_missing) > 0 OR v_n <> 3 OR to_regclass('public.briefing_deliveries_user_local_date_idx') IS NULL THEN
    RAISE EXCEPTION 'REFUSED (R2): stage is not bundle-applied (missing tables %, new columns %/3). Nothing to roll back, or a partial state: stop and escalate.', v_missing, v_n;
  END IF;

  -- [3] Nothing new may be destroyed (R3) -------------------------------------------
  v_counts := jsonb_build_object(
    'seed_pool_state',               (SELECT count(*) FROM public.seed_pool_state),
    'seed_pool_assets',              (SELECT count(*) FROM public.seed_pool_assets),
    'seed_pool_snapshots',           (SELECT count(*) FROM public.seed_pool_snapshots),
    'dashboard_batches',             (SELECT count(*) FROM public.dashboard_batches),
    'dashboard_deliveries',          (SELECT count(*) FROM public.dashboard_deliveries),
    'dashboard_rollover_candidates', (SELECT count(*) FROM public.dashboard_rollover_candidates),
    'briefing_rows_with_new_values', (SELECT count(*) FROM public.briefing_deliveries
                                       WHERE local_date IS NOT NULL OR seed_pool_version IS NOT NULL
                                          OR seed_revocation_generation <> 0),
    'seed_pool_observed_days',       (SELECT count(*) FROM public.seed_pool_observed_days));
  SELECT coalesce(array_agg(e.key ORDER BY e.key), '{}'::text[]) INTO v_blockers
    FROM jsonb_each_text(v_counts) AS e
   WHERE e.value::bigint > 0
     AND NOT (e.key = 'seed_pool_observed_days' AND v_allow_drop_observed_day_markers);

  IF has_table_privilege('storage.objects', 'SELECT') THEN
    EXECUTE 'SELECT count(*) FROM storage.objects WHERE bucket_id = ''private-uploads'' AND name LIKE ''seed-pool/%'''
      INTO v_storage;
    IF v_storage > 0 THEN
      v_blockers := v_blockers || 'storage_objects_under_seed-pool/'::text;
    END IF;
  ELSIF NOT v_storage_checked_in_ui THEN
    v_blockers := v_blockers || 'storage_objects_unreadable_check_Storage_UI_first'::text;
  END IF;
  v_counts := v_counts || jsonb_build_object('storage_objects_under_seed_pool_prefix', v_storage);

  IF cardinality(v_blockers) > 0 AND v_target = 'production' THEN
    RAISE EXCEPTION 'REFUSED (R3): the new code already wrote data that this rollback would destroy: % (counts %). Do NOT force it. Keep the schema and roll back only the app (RUNBOOK.md H), or ask the user about forward-fix / backup restore.',
      v_blockers, v_counts;
  END IF;

  SELECT count(*) INTO v_bd_before FROM public.briefing_deliveries;

  -- [4] Undo the bundle ---------------------------------------------------------------
  -- Functions first (plpgsql bodies record no dependencies; RESTRICT stops on any
  -- unexpected dependent object and rolls everything back).
  DROP FUNCTION public.seed_pool_finish_asset(uuid, uuid);
  DROP FUNCTION public.seed_pool_put_private_pool(uuid, date, text, bigint, text, jsonb);
  DROP FUNCTION public.seed_pool_persist_digest_email(uuid, date, bigint, text, bigint, jsonb);
  DROP FUNCTION public.seed_pool_record_feed_served(uuid, date, text, bigint);
  DROP FUNCTION public.seed_pool_claim_cleanup(integer);
  DROP FUNCTION public.seed_pool_validate_digest_send(uuid, date, bigint, text, bigint);
  DROP FUNCTION public.seed_pool_claim_digest(uuid, date, text, bigint, text, text[], jsonb);
  DROP FUNCTION public.seed_pool_stage_asset(uuid, bigint, uuid, text, text, text, text, jsonb, jsonb, text);
  DROP FUNCTION public.seed_pool_editor(uuid);
  DROP FUNCTION public.seed_pool_ack_batch(uuid, date, uuid, text, bigint);
  DROP FUNCTION public.seed_pool_put_prepared_batch(uuid, date, text, bigint, text, jsonb, jsonb);
  DROP FUNCTION public.seed_pool_mark_batch_served(uuid, date, uuid, text, bigint);
  DROP FUNCTION public.seed_pool_fence_matches(uuid, date, text, bigint);
  DROP FUNCTION public.seed_pool_forget(uuid, bigint, uuid);
  DROP FUNCTION public.seed_pool_apply(uuid, bigint, uuid[], boolean);
  DROP FUNCTION public.seed_pool_resolve(uuid, date, timestamptz);
  DROP FUNCTION public.upsert_rollover_candidates(uuid, text, jsonb);
  DROP FUNCTION public.claim_briefing_delivery(uuid, text, text, text[], jsonb);
  DROP FUNCTION public.acknowledge_dashboard_batch(uuid, uuid);

  -- New tables, children before parents (RESTRICT; their policies/indexes go with them).
  DROP TABLE public.dashboard_deliveries;
  DROP TABLE public.dashboard_batches;
  DROP TABLE public.dashboard_rollover_candidates;
  DROP TABLE public.seed_pool_snapshots;
  DROP TABLE public.seed_pool_assets;
  DROP TABLE public.seed_pool_observed_days;
  DROP TABLE public.seed_pool_state;

  -- The existing table: only what the bundle added.
  DROP INDEX public.briefing_deliveries_user_local_date_idx;
  ALTER TABLE public.briefing_deliveries
    DROP COLUMN seed_revocation_generation,
    DROP COLUMN seed_pool_version,
    DROP COLUMN local_date;

  -- [5] Verify the pre-bundle shape before letting anything commit -------------------
  SELECT count(*) INTO v_bd_after FROM public.briefing_deliveries;
  IF v_bd_after <> v_bd_before THEN
    RAISE EXCEPTION 'ABORTED: briefing_deliveries row count changed (% -> %). Everything rolled back.', v_bd_before, v_bd_after;
  END IF;
  SELECT coalesce(array_agg(x ORDER BY x), '{}'::text[]) INTO v_left FROM (
    SELECT c.relname::text AS x FROM pg_class c
     WHERE c.relnamespace = 'public'::regnamespace AND (c.relname LIKE 'dashboard%' OR c.relname LIKE 'seed_pool%')
    UNION ALL
    SELECT p.proname::text FROM pg_proc p
     WHERE p.pronamespace = 'public'::regnamespace
       AND p.proname NOT IN ('handle_new_user', 'increment_usage_counter', 'touch_updated_at')
    UNION ALL
    SELECT 'briefing_deliveries.' || column_name::text FROM information_schema.columns
     WHERE table_schema = 'public' AND table_name = 'briefing_deliveries'
       AND column_name IN ('local_date', 'seed_pool_version', 'seed_revocation_generation')
    UNION ALL
    SELECT 'index:' || indexname::text FROM pg_indexes
     WHERE schemaname = 'public' AND tablename = 'briefing_deliveries'
       AND indexname NOT IN ('briefing_deliveries_pkey', 'briefing_deliveries_user_time_idx')) AS leftovers;
  IF cardinality(v_left) > 0 AND v_target = 'production' THEN
    RAISE EXCEPTION 'ABORTED: objects outside the pre-bundle shape remain: %. Everything rolled back.', v_left;
  END IF;
  SELECT count(*) INTO v_n FROM pg_policies WHERE schemaname = 'public';
  IF v_n <> 19 AND v_target = 'production' THEN
    RAISE EXCEPTION 'ABORTED: public has % policies, pre-bundle production had 19. Everything rolled back.', v_n;
  END IF;
  IF (SELECT array_to_string(relacl, ',') FROM pg_class WHERE oid = 'public.briefing_deliveries_id_seq'::regclass)
       IS DISTINCT FROM 'postgres=rwU/postgres,anon=rwU/postgres,authenticated=rwU/postgres,service_role=rwU/postgres' THEN
    RAISE EXCEPTION 'ABORTED: briefing_deliveries_id_seq ACL differs from the export. Everything rolled back.';
  END IF;

  -- [6] Dry run ends here, on purpose --------------------------------------------------
  -- Fail closed: anything other than exactly 'execute' on 'production' rolls back.
  IF v_mode IS DISTINCT FROM 'execute' OR v_target IS DISTINCT FROM 'production' THEN
    RAISE EXCEPTION 'PEER_ROLLBACK_DRY_RUN_OK (intentional error; everything rolled back, nothing changed): %',
      jsonb_build_object('target', v_target, 'r3_blockers', v_blockers, 'counts', v_counts,
                         'briefing_deliveries_rows_before_and_after', v_bd_before,
                         'objects_left_outside_pre_bundle_shape', v_left);
  END IF;
  RAISE NOTICE 'PEER_ROLLBACK_EXECUTED: bundle objects removed; briefing_deliveries rows kept: %', v_bd_after;
END
$rollback$;

-- Runs only after an EXECUTE that committed (a dry run or any refusal stops above).
SELECT jsonb_build_object(
  'rollback', 'COMMITTED',
  'stage_now', CASE WHEN to_regclass('public.seed_pool_state') IS NULL AND to_regclass('public.dashboard_batches') IS NULL
                     AND NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public'
                                       AND table_name = 'briefing_deliveries' AND column_name = 'local_date')
                    THEN 'pre-bundle' ELSE 'NOT pre-bundle - STOP' END,
  'next', 'run 01-preflight-readonly.sql: every stop_check must be true again'
) AS production_rollback;
