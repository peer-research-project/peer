  IF to_regclass('public.dashboard_batches') IS NOT NULL OR to_regclass('public.seed_pool_state') IS NOT NULL
     OR to_regclass('public.dashboard_deliveries') IS NOT NULL OR to_regclass('public.dashboard_rollover_candidates') IS NOT NULL
     OR to_regclass('public.seed_pool_observed_days') IS NOT NULL OR to_regclass('public.seed_pool_assets') IS NOT NULL
