-- 01-preflight-readonly.sql
-- PURPOSE: the last read-only look at PRODUCTION (gdakokshfjqljddlrkrh) right
--          before the canonical bundle is applied. It answers three questions in
--          ONE JSON cell:
--            1. Is production still exactly the shape the rehearsals were built
--               from (the 2026-11-03 read-only exports)?          -> stop_checks
--            2. Is it a safe moment to take the bundle's locks?   -> apply_wait
--            3. Will the NEW app code work for every account once the schema
--               exists?                                          -> deploy_decisions
--          plus verbatim re-captures of the five read-only verifier queries for the
--          offline comparison with the saved exports            -> export_copies
-- READ ONLY. No DDL, no DML, no temp objects. Reads catalogs, storage.buckets
--          metadata, pg_stat_activity/pg_locks COUNTS, and COUNTS over
--          auth.users / public.profiles / public.briefing_deliveries.
--          It returns no application or auth row and no row identifier.
-- GUARD FIRST: the DO block below is a verbatim copy of 00-production-guard.sql;
--          the second DO block refuses unless the stage is "pre-bundle".
--
-- HOW TO READ THE RESULT (cell `production_preflight`):
--   go_for_apply = true   -> every stop_check is true AND no long-running client
--                            transaction was seen. Proceed to the bundle.
--   go_for_apply = false  -> STOP. Do not apply. Report which key is false/non-zero.
--   stop_checks.*         -> each must be true. Any false = production drifted from
--                            the exports the bundle was rehearsed against. STOP.
--   apply_wait.long_running_client_transactions > 0
--                         -> wait 2-3 minutes and re-run 01; do not apply while an
--                            old transaction could hold briefing_deliveries.
--   apply_wait.other_sessions_holding_locks_on_*
--                         -> informational. The bundle takes ACCESS EXCLUSIVE on
--                            briefing_deliveries and SHARE ROW EXCLUSIVE on auth.users
--                            (its 7 new foreign keys to auth.users) until COMMIT, so
--                            sign-up/sign-in writes wait for the apply; pick a quiet
--                            minute (RUNBOOK.md D4 and E2a).
--   deploy_decisions.*    -> do NOT block the database apply (old code ignores the
--                            new objects), but each non-zero count BLOCKS the Vercel
--                            deploy until the user decides: such accounts would get
--                            HTTP 503 from /api/feed under the new code because
--                            seed_pool_resolve returns "unavailable" for an owner
--                            with no profile row or an unusable timezone
--                            (bundle lines 554-555, 565-566; web/src/app/api/feed/route.ts:288-289,85-89).
--                            The timezone count is an UPPER BOUND: it accepts zone
--                            names and abbreviations case-insensitively, but AT TIME
--                            ZONE also accepts POSIX-style specs (e.g. 'UTC+5'), which
--                            it still counts. It never under-counts.
--   export_copies.*       -> save the cell, split it (RUNBOOK.md step D3) and compare
--                            with %TEMP%\peer-rollout-evidence\production-*.json.
--                            Every compared category must match; postgres_version is
--                            not compared (a Supabase minor upgrade is not drift).
--
-- The expected literals below come from the read-only exports of 2026-11-03:
--   production-inventory-readonly.json   (20:15 UTC)  tables/policies/triggers/functions/buckets/ledger
--   production-security-metadata.json    (17:41 UTC)  RLS flags, owners, trigger, auth.uid ACL
--   production-sequence-metadata.json    (20:04 UTC)  briefing_deliveries_id_seq + postgres role
--   production-schema-metadata.json      (17:33 UTC)  columns/indexes/constraints (subset inline; full set offline)
--   test-project/production-default-privileges.json (20:45 UTC) default ACLs, event triggers
-- The embedded export_copies bodies are byte-identical to the SELECTs in
-- docs/handoff/upload-abstract/test-project/02,03,04,06,07 (header comments and the
-- final semicolon removed), generated by script, not retyped.
-- No psql meta-commands: paste-safe for the Supabase SQL Editor (role postgres).

DO $guard$
DECLARE
  v_expected_versions CONSTANT text[] := ARRAY[
    '20260424083636','20260428073641','20260429044039','20260505063457','20260915042700',
    '20260915042730','20260915042732','20260915042735','20260915042738','20260915042741',
    '20260915042812'];
  v_versions text[];
  v_users    bigint;
  v_oldest   timestamptz;
  v_missing  text[];
BEGIN
  IF current_user <> 'postgres' THEN
    RAISE EXCEPTION 'REFUSED (G1): run as role postgres; current_user=%.', current_user;
  END IF;

  IF to_regnamespace('peer_test_guard') IS NOT NULL THEN
    RAISE EXCEPTION 'REFUSED (G2): schema peer_test_guard exists. This is the peer-test project (cbsbtkvbmvyznerbpmxg), NOT production. Stop.';
  END IF;

  IF to_regclass('supabase_migrations.schema_migrations') IS NULL THEN
    RAISE EXCEPTION 'REFUSED (G3): supabase_migrations.schema_migrations is absent; production has an 11-row ledger. Stop.';
  END IF;
  EXECUTE 'SELECT coalesce(array_agg(version::text ORDER BY version::text), ''{}''::text[]) FROM supabase_migrations.schema_migrations'
    INTO v_versions;
  IF v_versions IS DISTINCT FROM v_expected_versions THEN
    RAISE EXCEPTION 'REFUSED (G3): migration ledger differs from the production export (rows=%, last=%). Expected exactly 11 rows ending 20260915042812. Stop and re-check the project.',
      coalesce(array_length(v_versions, 1), 0), v_versions[array_length(v_versions, 1)];
  END IF;

  SELECT count(*), min(created_at) INTO v_users, v_oldest FROM auth.users;
  IF v_users = 0 OR v_oldest IS NULL OR v_oldest >= timestamptz '2026-11-03 00:00:00+00' THEN
    RAISE EXCEPTION 'REFUSED (G4): auth.users has no account created before 2026-11-03 UTC; production has older accounts. Stop.';
  END IF;

  SELECT coalesce(array_agg(t ORDER BY t), '{}'::text[]) INTO v_missing
    FROM unnest(ARRAY['briefing_deliveries','feedback_events','opportunity_pools','private_decisions',
                      'private_paper_pools','profiles','read_items','saved_items','usage_counters']) AS t
   WHERE to_regclass('public.' || t) IS NULL;
  IF cardinality(v_missing) > 0 THEN
    RAISE EXCEPTION 'REFUSED (G5): production public tables missing: %. Stop.', v_missing;
  END IF;

  IF NOT EXISTS (SELECT 1 FROM storage.buckets
                  WHERE id = 'private-uploads' AND public = false AND file_size_limit = 26214400) THEN
    RAISE EXCEPTION 'REFUSED (G6): private bucket private-uploads (26214400 bytes) not found as exported. Stop.';
  END IF;
END
$guard$;

