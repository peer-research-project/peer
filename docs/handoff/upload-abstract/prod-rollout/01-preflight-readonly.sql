SELECT jsonb_build_object(
  'go_for_apply',
    (SELECT bool_and(coalesce(e.value::boolean, false)) FROM stop_all, jsonb_each_text(stop_all.j) AS e)
    AND ((SELECT j FROM apply_wait)->>'long_running_client_transactions')::bigint = 0,
  'stop_checks', (SELECT j FROM stop_all),
  'apply_wait', (SELECT j FROM apply_wait),
  'deploy_decisions', (SELECT j FROM deploy_decisions),
  'counts', (SELECT j FROM counts),
  'export_copies', jsonb_build_object(
    'schema_metadata', (
with wanted_tables(table_schema,table_name) as (
  values ('public','profiles'),('public','dashboard_batches'),
    ('public','dashboard_deliveries'),('public','briefing_deliveries'),
    ('public','private_paper_pools'),('public','dashboard_rollover_candidates')
), columns_metadata as (
  select c.table_schema,c.table_name,c.column_name,c.data_type,c.udt_name,
    c.is_nullable,c.column_default,c.ordinal_position
  from information_schema.columns c
  where (c.table_schema,c.table_name) in (select * from wanted_tables)
    or (c.table_schema='auth' and c.table_name='users' and c.column_name='id')
), constraints_metadata as (
  select n.nspname as table_schema,c.relname as table_name,k.conname,k.contype,
    pg_get_constraintdef(k.oid,true) as definition
  from pg_constraint k join pg_class c on c.oid=k.conrelid
    join pg_namespace n on n.oid=c.relnamespace
  where (n.nspname,c.relname) in (select * from wanted_tables)
), functions_metadata as (
  select n.nspname as schema_name,p.proname,
    pg_get_function_identity_arguments(p.oid) as arguments,
    pg_get_function_result(p.oid) as result,p.prosecdef,
    coalesce(array_to_string(p.proacl,','),'DEFAULT') as acl,
    pg_get_functiondef(p.oid) as definition
  from pg_proc p join pg_namespace n on n.oid=p.pronamespace
  where (n.nspname='auth' and p.proname='uid')
    or (n.nspname='public' and p.proname in
      ('acknowledge_dashboard_batch','claim_briefing_delivery'))
), policies_metadata as (
  select schemaname,tablename,policyname,roles,cmd,qual,with_check
  from pg_policies where (schemaname,tablename) in (select * from wanted_tables)
), grants_metadata as (
  select table_schema,table_name,grantee,privilege_type
  from information_schema.role_table_grants
  where (table_schema,table_name) in (select * from wanted_tables)
    and grantee in ('anon','authenticated','service_role','PUBLIC')
), indexes_metadata as (
  select schemaname,tablename,indexname,indexdef
  from pg_indexes where (schemaname,tablename) in (select * from wanted_tables)
), roles_metadata as (
  select rolname,rolsuper,rolinherit,rolcreaterole,rolcreatedb,rolcanlogin,rolbypassrls
  from pg_roles where rolname in ('anon','authenticated','service_role')
)
select jsonb_build_object(
  'postgres_version',version(),
  'columns',(select coalesce(jsonb_agg(to_jsonb(x) order by x.table_schema,x.table_name,x.ordinal_position),'[]'::jsonb) from columns_metadata x),
  'constraints',(select coalesce(jsonb_agg(to_jsonb(x) order by x.table_schema,x.table_name,x.conname),'[]'::jsonb) from constraints_metadata x),
  'functions',(select coalesce(jsonb_agg(to_jsonb(x) order by x.schema_name,x.proname,x.arguments),'[]'::jsonb) from functions_metadata x),
  'policies',(select coalesce(jsonb_agg(to_jsonb(x) order by x.schemaname,x.tablename,x.policyname),'[]'::jsonb) from policies_metadata x),
  'grants',(select coalesce(jsonb_agg(to_jsonb(x) order by x.table_schema,x.table_name,x.grantee,x.privilege_type),'[]'::jsonb) from grants_metadata x),
  'indexes',(select coalesce(jsonb_agg(to_jsonb(x) order by x.schemaname,x.tablename,x.indexname),'[]'::jsonb) from indexes_metadata x),
  'roles',(select coalesce(jsonb_agg(to_jsonb(x) order by x.rolname),'[]'::jsonb) from roles_metadata x)
) as schema_metadata
    ),
    'security_metadata', (
with wanted as (
  select c.oid,c.relname,c.relrowsecurity,c.relforcerowsecurity,
    pg_get_userbyid(c.relowner) as owner
  from pg_class c join pg_namespace n on n.oid=c.relnamespace
  where n.nspname='public' and c.relname in
    ('profiles','briefing_deliveries','private_paper_pools')
), triggers_metadata as (
  select w.relname as table_name,t.tgname,t.tgenabled,
    pg_get_triggerdef(t.oid,true) as definition,
    n.nspname as function_schema,p.proname,
    pg_get_userbyid(p.proowner) as function_owner,
    coalesce(array_to_string(p.proacl,','),'DEFAULT') as function_acl,
    pg_get_functiondef(p.oid) as function_definition
  from wanted w join pg_trigger t on t.tgrelid=w.oid and not t.tgisinternal
    join pg_proc p on p.oid=t.tgfoid
    join pg_namespace n on n.oid=p.pronamespace
), functions_metadata as (
  select n.nspname,p.proname,pg_get_userbyid(p.proowner) as owner,
    coalesce(array_to_string(p.proacl,','),'DEFAULT') as acl
  from pg_proc p join pg_namespace n on n.oid=p.pronamespace
  where n.nspname='auth' and p.proname='uid'
)
select jsonb_build_object(
  'tables',(select coalesce(jsonb_agg(to_jsonb(w)-'oid' order by w.relname),'[]'::jsonb) from wanted w),
  'triggers',(select coalesce(jsonb_agg(to_jsonb(t) order by t.table_name,t.tgname),'[]'::jsonb) from triggers_metadata t),
  'auth_functions',(select coalesce(jsonb_agg(to_jsonb(f)),'[]'::jsonb) from functions_metadata f),
  'seed_objects',jsonb_build_object(
    'state',to_regclass('public.seed_pool_state')::text,
    'assets',to_regclass('public.seed_pool_assets')::text,
    'snapshots',to_regclass('public.seed_pool_snapshots')::text,
    'observed_days',to_regclass('public.seed_pool_observed_days')::text)
) as security_metadata
    ),
    'sequence_metadata', (
with target as (
  select pg_get_serial_sequence('public.briefing_deliveries','id')::regclass as oid
)
select jsonb_build_object(
  'current_user',current_user,
  'postgres_role',(select jsonb_build_object('rolsuper',r.rolsuper,'rolinherit',r.rolinherit,'rolcreaterole',r.rolcreaterole,'rolcreatedb',r.rolcreatedb,'rolcanlogin',r.rolcanlogin,'rolbypassrls',r.rolbypassrls) from pg_roles r where r.rolname='postgres'),
  'postgres_auth_usage',has_schema_privilege('postgres','auth','USAGE'),
  'postgres_auth_users_references',has_table_privilege('postgres','auth.users','REFERENCES'),
  'postgres_public_create',has_schema_privilege('postgres','public','CREATE'),
  'sequence_name',t.oid::text,
  'owner',pg_get_userbyid(c.relowner),
  'acl',coalesce(array_to_string(c.relacl,','),'DEFAULT'),
  'type',format_type(s.seqtypid,null),
  'start',s.seqstart,'increment',s.seqincrement,'minimum',s.seqmin,
  'maximum',s.seqmax,'cache',s.seqcache,'cycle',s.seqcycle,
  'service_usage',has_sequence_privilege('service_role',t.oid,'USAGE'),
  'service_select',has_sequence_privilege('service_role',t.oid,'SELECT'),
  'authenticated_usage',has_sequence_privilege('authenticated',t.oid,'USAGE'),
  'anon_usage',has_sequence_privilege('anon',t.oid,'USAGE')
) as sequence_metadata
from target t left join pg_class c on c.oid=t.oid
  left join pg_sequence s on s.seqrelid=t.oid
    ),
    'inventory', (
SELECT jsonb_build_object(
  'tables', (SELECT coalesce(jsonb_agg(c.relname ORDER BY c.relname), '[]'::jsonb)
             FROM pg_class c
             WHERE c.relnamespace = 'public'::regnamespace AND c.relkind IN ('r', 'p')),
  'buckets', (SELECT coalesce(jsonb_agg(b.id || ':' || b.public::text || ':' || coalesce(b.file_size_limit::text, 'null') ORDER BY b.id), '[]'::jsonb)
              FROM storage.buckets b),
  'policies', (SELECT coalesce(jsonb_agg(p.tablename || ':' || p.policyname ORDER BY p.tablename, p.policyname), '[]'::jsonb)
               FROM pg_policies p WHERE p.schemaname = 'public'),
  'triggers', (SELECT coalesce(jsonb_agg(c.relname || ':' || t.tgname ORDER BY c.relname, t.tgname), '[]'::jsonb)
               FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
               WHERE NOT t.tgisinternal
                 AND (c.relnamespace = 'public'::regnamespace OR t.tgrelid = 'auth.users'::regclass)),
  'functions', (SELECT coalesce(jsonb_agg(p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')' ORDER BY p.proname, pg_get_function_identity_arguments(p.oid)), '[]'::jsonb)
                FROM pg_proc p WHERE p.pronamespace = 'public'::regnamespace),
  'migrations_table', CASE WHEN to_regclass('supabase_migrations.schema_migrations') IS NULL
                           THEN NULL ELSE 'supabase_migrations.schema_migrations' END,
  'absent_on_production_check', jsonb_build_object(
    'briefing_deliveries_local_date', EXISTS (SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'briefing_deliveries' AND column_name = 'local_date'),
    'dashboard_tables', (SELECT count(*) FROM pg_class WHERE relnamespace = 'public'::regnamespace AND relname LIKE 'dashboard%' AND relkind = 'r'),
    'seed_pool_tables', (SELECT count(*) FROM pg_class WHERE relnamespace = 'public'::regnamespace AND relname LIKE 'seed_pool%' AND relkind = 'r')),
  'storage_objects_policies', (SELECT coalesce(jsonb_agg(policyname ORDER BY policyname), '[]'::jsonb)
                               FROM pg_policies WHERE schemaname = 'storage' AND tablename = 'objects')
) AS inventory
    ),
    'default_privileges_metadata', (
SELECT jsonb_build_object(
  'postgres_version', version(),
  'current_user', current_user,
  'default_acls', (
    SELECT coalesce(jsonb_agg(jsonb_build_object(
             'role', pg_get_userbyid(d.defaclrole),
             'schema', coalesce(n.nspname, '<all schemas>'),
             'objtype', CASE d.defaclobjtype WHEN 'r' THEN 'tables' WHEN 'S' THEN 'sequences'
                          WHEN 'f' THEN 'functions' WHEN 'T' THEN 'types' WHEN 'n' THEN 'schemas'
                          ELSE d.defaclobjtype::text END,
             'acl', array_to_string(d.defaclacl, ','))
           ORDER BY pg_get_userbyid(d.defaclrole), coalesce(n.nspname, ''), d.defaclobjtype), '[]'::jsonb)
    FROM pg_default_acl d LEFT JOIN pg_namespace n ON n.oid = d.defaclnamespace
    WHERE pg_get_userbyid(d.defaclrole) IN ('postgres', 'supabase_admin')
      AND (n.nspname IS NULL OR n.nspname = 'public')),
  'event_triggers', (
    SELECT coalesce(jsonb_agg(jsonb_build_object(
             'name', e.evtname, 'event', e.evtevent, 'enabled', e.evtenabled,
             'function', e.evtfoid::regproc::text, 'tags', e.evttags)
           ORDER BY e.evtname), '[]'::jsonb)
    FROM pg_event_trigger e),
  'public_schema_acl', (SELECT array_to_string(nspacl, ',') FROM pg_namespace WHERE nspname = 'public'),
  'postgres_can_set_role', jsonb_build_object(
    'anon', pg_has_role('postgres', 'anon', 'MEMBER'),
    'authenticated', pg_has_role('postgres', 'authenticated', 'MEMBER'),
    'service_role', pg_has_role('postgres', 'service_role', 'MEMBER')),
  'auth_users_triggers_owner_privilege', jsonb_build_object(
    'auth_users_owner', (SELECT pg_get_userbyid(relowner) FROM pg_class WHERE oid = 'auth.users'::regclass),
    'postgres_trigger_on_auth_users', has_table_privilege('postgres', 'auth.users', 'TRIGGER'),
    'postgres_references_auth_users', has_table_privilege('postgres', 'auth.users', 'REFERENCES')),
  'storage_buckets_privileges', jsonb_build_object(
    'insert', has_table_privilege('postgres', 'storage.buckets', 'INSERT'),
    'select', has_table_privilege('postgres', 'storage.buckets', 'SELECT'))
) AS default_privileges_metadata
    ))
) AS production_preflight;
